import requests
import pandas as pd
from sklearn.preprocessing import LabelEncoder
import time
import warnings
warnings.filterwarnings('ignore')

print('?? ????? ????? ??????: ???? ????? ??? ????????...')
df = pd.read_csv('UNSW_NB15_training-set.csv', nrows=5)

if 'id' in df.columns: df = df.drop(columns=['id'])
if 'attack_cat' in df.columns: df = df.drop(columns=['attack_cat'])
if 'label' in df.columns: df = df.drop(columns=['label'])

categorical_cols = df.select_dtypes(include=['object', 'string']).columns
encoder = LabelEncoder()
for col in categorical_cols:
    df[col] = encoder.fit_transform(df[col].astype(str))

print('?? ??? ???? ???????? ??? ???? SOC (???? ?? ???????)...\n' + '-'*50)

for index, row in df.iterrows():
    network_packet = row.to_dict()
    # ?????? ?????? IP ?????? ??? ???? ?????? ???? ???????
    network_packet['srcip'] = f'192.168.1.{50 + index}'
    
    try:
        response = requests.post('http://127.0.0.1:8000/analyze', json=network_packet)
        result = response.json()
        
        if result.get('threat_detected'):
            print(f"[{index+1}] ?? ???? ?????! | ???????: {result.get('action_taken')} | ?????? ?????????: {result.get('total_blocked_ips')}")
        else:
            print(f"[{index+1}] ? ???? ???? ?????? | IP: {network_packet['srcip']}")
            
    except requests.exceptions.ConnectionError:
        print(f"[{index+1}] ? ???? ??????? ???????.")
        
    time.sleep(2)

print('-'*50 + '\n? ????? ?????.')
